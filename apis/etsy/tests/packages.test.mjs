import assert from 'node:assert/strict';
import { readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const PYTHON = join(ROOT, 'apis/etsy/packages/python');
const GO = join(ROOT, 'apis/etsy/packages/go');
const AFFILIATION = /not affiliated with.*Etsy/i;
// Etsy's API terms require this notice wherever the app is described.
const TRADEMARK = "The term 'Etsy' is a trademark of Etsy, Inc. This Application uses Etsy's API, but is not endorsed or certified by Etsy.";

const unwrapped = async (path) => (await readFile(path, 'utf8')).replace(/\s+/g, ' ');

test('the Python package ships the Apache-2.0 licence and a notice for Etsy', async () => {
  assert.equal(await readFile(join(PYTHON, 'LICENSE'), 'utf8'), await readFile(join(ROOT, 'LICENSE'), 'utf8'));
  const notice = await unwrapped(join(PYTHON, 'NOTICE'));
  assert.match(notice, AFFILIATION);
  assert.ok(notice.includes(TRADEMARK));
  assert.doesNotMatch(notice, /back ?market/i);
});

test('the Python manifest declares Apache-2.0, the approved name and says it is unofficial', async () => {
  const manifest = await readFile(join(PYTHON, 'pyproject.toml'), 'utf8');
  assert.match(manifest, /^license = "Apache-2\.0"$/m);
  assert.match(manifest, /^license-files = \["LICENSE", "NOTICE"\]$/m);
  assert.match(manifest, /^name = "etsy-seller"$/m);
  assert.match(manifest.match(/^description = .*$/m)[0], /Unofficial.*not affiliated with Etsy/i);
});

test('the Python package is marked as typed', async () => {
  assert.equal(await readFile(join(PYTHON, 'src/etsy_seller/py.typed'), 'utf8'), '');
});

test('the Python README says it is unofficial, carries the trademark notice and the terms users must follow', async () => {
  const readme = await unwrapped(join(PYTHON, 'README.md'));
  assert.match(readme, AFFILIATION);
  assert.ok(readme.includes(TRADEMARK));
  assert.match(readme, /6 hours/);
  assert.match(readme, /scraping/);
  assert.match(readme, /train AI/);
});

test('generated Python carries no upstream prose', async () => {
  const dir = join(PYTHON, 'src/etsy_seller');
  const entries = await readdir(dir, { recursive: true, withFileTypes: true });
  const offenders = [];
  for (const entry of entries.filter((item) => item.isFile() && item.name.endsWith('.py'))) {
    const path = join(entry.parentPath, entry.name);
    if (path.includes('/api/') || path.includes('/models/')) {
      if (/Field\([^)]*description=|json_schema_extra|Etsy, Inc/i.test(await readFile(path, 'utf8'))) offenders.push(path);
    }
  }
  assert.deepEqual(offenders, []);
});

test('the Go module ships the Apache-2.0 licence and a notice for Etsy', async () => {
  assert.equal(await readFile(join(GO, 'LICENSE'), 'utf8'), await readFile(join(ROOT, 'LICENSE'), 'utf8'));
  assert.equal(await readFile(join(GO, 'NOTICE'), 'utf8'), await readFile(join(PYTHON, 'NOTICE'), 'utf8'));
});

test('the Go manifest declares Apache-2.0, the approved name and says it is unofficial', async () => {
  const manifest = await readFile(join(GO, 'go.mod'), 'utf8');
  assert.match(manifest, /^\/\/ SPDX-License-Identifier: Apache-2\.0$/m);
  assert.match(manifest, /^\/\/ Unofficial.*not affiliated with Etsy\.$/im);
  const doc = await unwrapped(join(GO, 'etsyseller/doc.go'));
  assert.match(doc, /^\/\/ Package etsyseller is an unofficial client/);
  assert.match(doc.replaceAll('// ', ''), /not affiliated with,[^.]*Etsy/);
  assert.ok(doc.replaceAll(' // ', ' ').includes(TRADEMARK));
});

test('the Go README says it is unofficial, carries the trademark notice and the terms users must follow', async () => {
  const readme = await unwrapped(join(GO, 'README.md'));
  assert.match(readme, AFFILIATION);
  assert.ok(readme.includes(TRADEMARK));
  assert.match(readme, /6 hours/);
  assert.match(readme, /scraping/);
  assert.match(readme, /train AI/);
});

test('generated Go carries no upstream prose', async () => {
  const dir = join(GO, 'etsyseller');
  const ours = /^\/\/ (Code generated by OpenAPI Generator|[A-Z]\w+ (is an API object|is an enumerated value|groups the|holds the (query parameters|form fields)( and form fields)? of|iterates every item|decodes tolerantly|encodes the fields))/;
  const summaries = (await readFile(join(GO, 'operations.yaml'), 'utf8'))
    .match(/summary: [^}]*[^ }]/g)
    .map((line) => line.slice('summary: '.length).replace(/^"(.*)"$/, '$1'));
  const offenders = [];
  for (const name of await readdir(dir)) {
    if (!/^(api|model)_.*\.go$/.test(name)) continue;
    const text = await readFile(join(dir, name), 'utf8');
    const comments = text.match(/^\s*\/\/.*$/gm).map((line) => line.trim());
    const prose = comments.filter((line) => !ours.test(line) && !summaries.includes(line.slice(3)));
    if (/Etsy, Inc/i.test(text) || prose.length > 0) offenders.push(name);
  }
  assert.deepEqual(offenders, []);
});
