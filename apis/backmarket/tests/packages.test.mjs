test('the Go manifest declares Apache-2.0 and says it is unofficial', async () => {
  const manifest = await readFile(join(GO, 'go.mod'), 'utf8');
  assert.match(manifest, /^\/\/ SPDX-License-Identifier: Apache-2\.0$/m);
  assert.match(manifest, /^\/\/ Unofficial.*not affiliated with Back Market\.$/im);
  assert.match(await readFile(join(GO, 'README.md'), 'utf8'), AFFILIATION);
  assert.match(await readFile(join(GO, 'backmarketseller/doc.go'), 'utf8'), /not affiliated with,[^.]*Back Market/);
});

test('generated Go carries no upstream prose', async () => {
  const dir = join(GO, 'backmarketseller');
  const ours = /^\/\/ (Code generated by OpenAPI Generator|[A-Z]\w+ (is an API object|is an enumerated value|groups the|holds the (query parameters|form fields) of|iterates every item|decodes tolerantly|encodes the fields))/;
  const summaries = (await readFile(join(GO, 'operations.yaml'), 'utf8')).match(/summary: [^}]*[^ }]/g).map((line) => line.slice('summary: '.length));
  const offenders = [];
  for (const name of await readdir(dir)) {
    if (!/^(api|model)_.*\.go$/.test(name)) continue;
    const text = await readFile(join(dir, name), 'utf8');
    const comments = text.match(/^\s*\/\/.*$/gm).map((line) => line.trim());
    const prose = comments.filter((line) => !ours.test(line) && !summaries.includes(line.slice(3)));
    if (/back market/i.test(text) || prose.length > 0) offenders.push(name);
  }
  assert.deepEqual(offenders, []);
});

