  const summaries = [];
  for (const name of await readdir(join(CSHARP, 'operations'))) {
    const text = await readFile(join(CSHARP, 'operations', name), 'utf8');
    for (const line of text.match(/summary: [^}]*[^ }]/g) ?? []) summaries.push(line.slice('summary: '.length).replace(/^"(.*)"$/, '$1'));
  }
  const dir = join(CSHARP, 'src/EbaySell');
