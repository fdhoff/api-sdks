test('generated Go carries no upstream prose', async () => {
  const ours = /^\/\/ (Code generated by OpenAPI Generator|[A-Z]\w+ (is an API object|is an enumerated value|groups the|holds the (parameters|query parameters|form fields)( and form fields)? of|iterates every item|decodes tolerantly|encodes the fields))/;
  const summaries = [];
  for (const name of await readdir(join(GO, 'operations'))) {
    const text = await readFile(join(GO, 'operations', name), 'utf8');
    for (const line of text.match(/summary: [^}]*[^ }]/g) ?? []) summaries.push(line.slice('summary: '.length).replace(/^"(.*)"$/, '$1'));
  }
  const entries = await readdir(join(GO, 'ebaysell'), { recursive: true, withFileTypes: true });
  const offenders = [];
  for (const entry of entries.filter((item) => item.isFile() && /^(api|model)_.*\.go$/.test(item.name))) {
    const path = join(entry.parentPath, entry.name);
    const text = await readFile(path, 'utf8');
    const comments = (text.match(/^\s*\/\/.*$/gm) ?? []).map((line) => line.trim());
    const prose = comments.filter((line) => !ours.test(line) && !summaries.includes(line.slice(3)));
    if (/eBay Inc/i.test(text) || prose.length > 0) offenders.push(path);
  }
  assert.deepEqual(offenders, []);
});

