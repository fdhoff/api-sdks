import assert from 'node:assert/strict';
import { readdir, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { test } from 'node:test';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const RUST = join(ROOT, 'apis/mirakl/packages/rust');
const AFFILIATION = 'Not affiliated with, endorsed by or sponsored by Mirakl SAS.';

const unwrapped = async (path) => (await readFile(path, 'utf8')).replace(/\s+/g, ' ');
const operations = parse(await readFile(join(RUST, 'operations.yaml'), 'utf8'));
const sdk = parse(await readFile(join(ROOT, 'apis/mirakl/sdk.yaml'), 'utf8'));

test('the Rust crate ships the Apache-2.0 licence and a notice that names Mirakl', async () => {
  assert.equal(await readFile(join(RUST, 'LICENSE'), 'utf8'), await readFile(join(ROOT, 'LICENSE'), 'utf8'));
  const notice = await unwrapped(join(RUST, 'NOTICE'));
  assert.match(notice, /not affiliated with, endorsed by or sponsored by Mirakl SAS/);
  assert.match(notice, /grants no right to the Mirakl name/);
});

test('the Rust manifest declares Apache-2.0, the approved name, a 0.x version and says it is unofficial', async () => {
  const manifest = await readFile(join(RUST, 'Cargo.toml'), 'utf8');
  assert.match(manifest, /^name = "mirakl-seller"$/m);
  assert.match(manifest, /^version = "0\./m);
  assert.match(manifest, /^license = "Apache-2\.0"$/m);
  const description = manifest.match(/^description = "(.*)"$/m)[1];
  assert.match(description, /^Unofficial /);
  assert.ok(description.includes(AFFILIATION));
  assert.match(manifest, /^include = .*"\/LICENSE", "\/NOTICE"\]$/m);
});

test('the Rust README says it is unofficial, that the base URL is per operator and that there is no sandbox', async () => {
  const readme = await unwrapped(join(RUST, 'README.md'));
  assert.match(readme, /^# mirakl-seller Unofficial /);
  assert.ok(readme.includes(AFFILIATION));
  assert.match(readme, /Best Buy/);
  assert.match(readme, /base URL is per operator/);
  assert.match(readme, /no public sandbox/);
  assert.match(readme, /0\.x/);
});

test('the Rust changelog leaves the first alpha unreleased, so no tag can publish it', async () => {
  const manifest = await readFile(join(RUST, 'Cargo.toml'), 'utf8');
  const version = manifest.match(/^version = "(.*)"$/m)[1];
  assert.ok((await readFile(join(RUST, 'CHANGELOG.md'), 'utf8')).includes(`## ${version} (unreleased)`));
});

test('generated Rust carries no upstream prose', async () => {
  const summaries = new Set(Object.values(operations).map(({ summary }) => `/// ${summary}`));
  const ours = [
    /^\/\/ Code generated by OpenAPI Generator \(https:\/\/openapi-generator\.tech\); DO NOT EDIT\.$/,
    /^\/\/\/ \w+ is an API object\. `extra` holds unknown fields, nulls, and any value that did not fit its field\.$/,
    /^\/\/\/ `None` sends the client's default, if it has one\.$/,
    /^\/\/\/ The (query parameters|form fields|query parameters and form fields) of \[`\w+::\w+`\]\. Set only what you need\.$/,
    /^\/\/\/ Iterates every item across all pages\. The stream ends after yielding an error\.$/,
    /^\/\/\/ The body arrives as a download, read as it arrives within the client's timeout\.$/,
    /^\/\/\/ The `\w+` operations, from \[`Client::\w+`\]\(crate::Client::\w+\)\.$/,
    /^\/\/\/ Polls every `options\.interval` until the job that `\w+` started ends, and returns$/,
    /^\/\/\/ its last status, done or failed\. Pass the `\w+` it returned\. Once `options\.timeout`$/,
    /^\/\/\/ passes, the error's kind is `JobTimeout` and \[`Error::job_status`\] holds the last status\.$/,
    /^\/\/\/ Every poll sends the client's query defaults\. Dropping the future stops it\.$/,
    /^\/\/\/$/,
  ];
  const offenders = [];
  for (const dir of ['src/apis', 'src/models']) {
    for (const name of await readdir(join(RUST, dir))) {
      const text = await readFile(join(RUST, dir, name), 'utf8');
      const comments = text.split('\n').map((line) => line.trim()).filter((line) => line.startsWith('//'));
      const foreign = comments.filter((line) => !summaries.has(line) && !ours.some((pattern) => pattern.test(line)));
      if (foreign.length > 0) offenders.push(`${dir}/${name}: ${foreign[0]}`);
    }
  }
  assert.deepEqual(offenders, []);
});

test('the conformance driver can call every operation, iterator and wait', async () => {
  const dispatch = await readFile(join(RUST, 'conformance/dispatch.rs'), 'utf8');
  const arms = [...dispatch.matchAll(/^\s*\("(\w+)", (true|false)\)( if case\.wait)? =>/gm)].map(
    ([, id, paginate, wait]) => `${id} ${wait ? 'wait' : paginate}`,
  );
  const expected = Object.entries(operations).flatMap(([id, names]) => [
    `${id} false`,
    ...(names.iterator ? [`${id} true`] : []),
    ...(names.wait ? [`${id} wait`] : []),
  ]);
  assert.equal(Object.keys(operations).length, 116);
  assert.equal(expected.length, 116 + Object.keys(sdk.iterators).length + Object.keys(sdk.jobs).length);
  assert.deepEqual(arms.sort(), expected.sort());
});
